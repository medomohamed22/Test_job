package com.tripmate.ai.data.account

import android.app.Activity
import android.content.Context
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.NoCredentialException
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.firebase.FirebaseApp
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.GoogleAuthProvider
import com.google.firebase.firestore.FirebaseFirestore
import com.tripmate.ai.domain.model.TripPlan
import dagger.hilt.android.qualifiers.ApplicationContext
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.tasks.await
import javax.inject.Inject
import javax.inject.Singleton

data class AccountUser(val uid: String, val displayName: String?, val email: String?)

/**
 * Optional account features. The app is guest-first: everything works locally without signing in.
 * Requires a google-services.json with Google sign-in enabled; otherwise [isAvailable] is false.
 */
@Singleton
class AccountRepository @Inject constructor(@ApplicationContext private val context: Context) {
    val isAvailable: Boolean get() = runCatching { FirebaseApp.getApps(context).isNotEmpty() }.getOrDefault(false)

    private val _user = MutableStateFlow<AccountUser?>(null)
    val user: StateFlow<AccountUser?> = _user.asStateFlow()

    init {
        if (isAvailable) runCatching {
            FirebaseAuth.getInstance().addAuthStateListener { auth ->
                _user.value = auth.currentUser?.takeIf { !it.isAnonymous }?.let { AccountUser(it.uid, it.displayName, it.email) }
            }
        }
    }

    /** Web client ID generated by the google-services plugin, looked up at runtime so builds without Firebase compile. */
    @Suppress("DiscouragedApi")
    private fun webClientId(): String? {
        val id = context.resources.getIdentifier("default_web_client_id", "string", context.packageName)
        return if (id != 0) context.getString(id) else null
    }

    suspend fun signInWithGoogle(activity: Activity): Result<AccountUser> = runCatching {
        check(isAvailable) { "Firebase is not configured" }
        val clientId = webClientId() ?: error("Google sign-in is not enabled for this Firebase project")
        val option = GetGoogleIdOption.Builder().setFilterByAuthorizedAccounts(false).setServerClientId(clientId).build()
        val result = try {
            CredentialManager.create(activity).getCredential(activity, GetCredentialRequest.Builder().addCredentialOption(option).build())
        } catch (e: NoCredentialException) {
            error("No Google account available on this device")
        }
        val cred = result.credential
        check(cred is CustomCredential && cred.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) { "Unexpected credential" }
        val google = GoogleIdTokenCredential.createFrom(cred.data)
        val user = FirebaseAuth.getInstance().signInWithCredential(GoogleAuthProvider.getCredential(google.idToken, null)).await().user
            ?: error("Sign-in failed")
        AccountUser(user.uid, user.displayName, user.email).also { _user.value = it }
    }

    fun signOut() {
        if (isAvailable) FirebaseAuth.getInstance().signOut()
        _user.value = null
    }

    /**
     * Backs up trip plans to Firestore under users/{uid}/trips. Coordinates are rounded to ~100 m
     * and journal photos are never uploaded.
     */
    suspend fun backupTrips(trips: List<TripPlan>): Result<Int> = runCatching {
        val uid = user.value?.uid ?: error("Not signed in")
        val col = FirebaseFirestore.getInstance().collection("users").document(uid).collection("trips")
        trips.forEach { t ->
            val doc = mapOf(
                "title" to t.title, "destination" to t.destinationName, "start" to t.startDate.toString(), "end" to t.endDate.toString(),
                "currency" to t.currency, "budget" to t.budgetTotal, "status" to t.status.name, "updatedAt" to t.updatedAt,
                "days" to t.days.map { d ->
                    mapOf("date" to d.date.toString(), "stops" to d.stops.map { s ->
                        mapOf("title" to s.title, "start" to s.startMinutes, "duration" to s.durationMinutes, "status" to s.status.name,
                            "lat" to s.lat?.let { Math.round(it * 1000) / 1000.0 }, "lng" to s.lng?.let { Math.round(it * 1000) / 1000.0 })
                    })
                },
            )
            col.document(t.id).set(doc).await()
        }
        trips.size
    }
}
